import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  evaluate, USES, USE_IDS, LICENCES, LICENCE_IDS, CAPABILITIES,
  type CulturalState, type Capability, type Sensitivity, type EvaluateInput,
} from '../src/lib/permissions';

const STATES: CulturalState[] = ['permitted', 'not_permitted', 'unspecified'];
const SENS: Sensitivity[] = ['public', 'handle_with_care', 'restricted'];

function* allInputs(): Generator<EvaluateInput> {
  const caps = CAPABILITIES;
  const combos: Record<Capability, CulturalState>[] = [];
  for (const a of STATES) for (const b of STATES) for (const c of STATES) for (const d of STATES)
    combos.push({ share: a, commercial: b, adapt: c, ai_training: d });
  for (const use of USE_IDS) for (const licence of LICENCE_IDS) for (const cultural of combos)
    for (const attributionRequired of [true, false]) for (const sensitivity of SENS)
      yield { use, licence, cultural, attributionRequired, sensitivity };
  void caps;
}
const base = (o: Partial<EvaluateInput>): EvaluateInput => ({
  use: 'print_merch', licence: 'CC-BY-4.0',
  cultural: { share: 'permitted', commercial: 'unspecified', adapt: 'unspecified', ai_training: 'unspecified' },
  attributionRequired: true, sensitivity: 'public', ...o,
});

test('property: invariants hold across every combination', () => {
  let n = 0;
  for (const inp of allInputs()) {
    n++;
    const out = evaluate(inp);
    const needs = USES[inp.use].needs;
    const licCells = needs.map((c) => LICENCES[inp.licence].cells[c]);   // data table, not engine logic
    const culStates = needs.map((c) => inp.cultural[c]);
    // any explicit "no" anywhere blocks
    if (licCells.includes('no') || culStates.includes('not_permitted')) assert.equal(out.verdict, 'not_permitted');
    // permitted requires every layer explicit yes
    if (out.verdict === 'permitted') {
      assert.ok(licCells.every((c) => c === 'yes'));
      assert.ok(culStates.every((s) => s === 'permitted'));
      assert.notEqual(inp.sensitivity, 'restricted');
    }
    // restricted never yields permitted
    if (inp.sensitivity === 'restricted') assert.notEqual(out.verdict, 'permitted');
    // unspecified culture never yields permitted
    if (culStates.includes('unspecified')) assert.notEqual(out.verdict, 'permitted');
    // always has a next action and guidance; available only when permitted
    assert.ok(out.nextAction.length > 10 && out.guidance.length > 10);
    assert.equal(out.available, out.verdict === 'permitted');
    // credit rule
    assert.equal(out.creditRequired, LICENCES[inp.licence].attribution || inp.attributionRequired);
    // statements always present
    assert.ok(out.licence.statement && out.cultural.statement);
  }
  assert.equal(n, 6 * 6 * 81 * 2 * 3);
});

// Hand-written golden cases (expected strings written by hand, not generated by the engine).
test('golden: commercial print, community silent -> Ask first with the plan sentence', () => {
  const out = evaluate(base({}));
  assert.equal(out.verdict, 'ask_first');
  assert.equal(
    out.guidance,
    'Print on merchandise (commercial): Ask first, because the community has not stated whether commercial use is acceptable. Next step: contact the stated custodian.',
  );
  assert.equal(out.cultural.statement, 'Not stated by the creator or community.');
});
test('golden: same use, three different verdicts (Tier A shape)', () => {
  const permitted = evaluate(base({ licence: 'CC-BY-4.0', cultural: { share: 'permitted', commercial: 'permitted', adapt: 'permitted', ai_training: 'unspecified' } }));
  const ask = evaluate(base({}));
  const no = evaluate(base({ licence: 'CC-BY-4.0', cultural: { share: 'permitted', commercial: 'not_permitted', adapt: 'unspecified', ai_training: 'unspecified' } }));
  assert.deepEqual([permitted.verdict, ask.verdict, no.verdict], ['permitted', 'ask_first', 'not_permitted']);
  assert.equal(permitted.creditRequired, true);
});
test('golden: NC licence blocks commercial even if community permits', () => {
  const out = evaluate(base({ licence: 'CC-BY-NC-4.0', cultural: { share: 'permitted', commercial: 'permitted', adapt: 'permitted', ai_training: 'permitted' } }));
  assert.equal(out.verdict, 'not_permitted');
  assert.equal(out.licence.verdict, 'not_permitted');
  assert.equal(out.cultural.verdict, 'permitted');
});
test('golden: CC0 + permitted culture + public -> permitted, credit not required by licence', () => {
  const out = evaluate(base({ licence: 'CC0', attributionRequired: false, use: 'share_online', cultural: { share: 'permitted', commercial: 'unspecified', adapt: 'unspecified', ai_training: 'unspecified' } }));
  assert.equal(out.verdict, 'permitted');
  assert.equal(out.creditRequired, false);
});
test('golden: restricted record asks first even when everything is permitted', () => {
  const out = evaluate(base({ licence: 'CC0', use: 'share_online', sensitivity: 'restricted', cultural: { share: 'permitted', commercial: 'permitted', adapt: 'permitted', ai_training: 'permitted' } }));
  assert.equal(out.verdict, 'ask_first');
  assert.match(out.guidance, /marked restricted/);
});
test('golden: share-alike note appears for remix on CC BY-SA', () => {
  const out = evaluate(base({ licence: 'CC-BY-SA-4.0', use: 'remix', cultural: { share: 'permitted', commercial: 'permitted', adapt: 'permitted', ai_training: 'permitted' } }));
  assert.ok(out.notes.some((n) => /share-alike/.test(n)));
});
